def _multi_step(rng: random.Random, i: int):
    vc = rng.randrange(80, 221, 5)
    d = rng.randint(8, 100)
    f = rng.choice([0.1, 0.12, 0.15, 0.2, 0.25, 0.3, 0.4])
    z = rng.randint(2, 6)
    length = rng.choice([50, 80, 100, 150, 200, 300, 500, 800])
    n = 1000.0 * vc / (math.pi * d)
    vf = f * z * n
    t = length / vf
    user = (f"车削/铣削综合计算：D={d} mm，Vc={vc} m/min，f={f} mm/z，z={z}，"
            f"行程 L={length} mm。请依次求主轴转速 n、进给速度 Vf 和加工时间 T，保留合适小数。")
    answer = (f"1) n = 1000×{vc}/(π×{d}) = {n:.1f} r/min\n"
              f"2) Vf = f×z×n = {f}×{z}×{n:.1f} = {vf:.1f} mm/min\n"
              f"3) T = L/Vf = {length}/{vf:.1f} = {t:.2f} min\n"
              f"注意：T 未计入换刀、空行程和装夹时间。")
    return _msg(user, answer, "reasoning_multi_step")


