def all_atoms() -> List[Dict[str, Any]]:
    """扁平化全部原子，附带所属族信息（family / family_title）。"""
    out: List[Dict[str, Any]] = []
    for fam in FAMILIES:
        for atom in fam["atoms"]:
            item = dict(atom)
            item["family"] = fam["id"]
            item["family_title"] = fam["title"]
            out.append(item)
    return out


def export_json(path: str | Path | None = None) -> Path:
    """导出机器可读目录，供非 Python 运行时（模型提示、前端、外部 agent）消费。"""
    target = Path(path) if path else Path(__file__).with_name("registry.json")
    payload = {
        "version": CATALOG_VERSION,
        "family_count": len(FAMILIES),
        "atom_count": len(all_atoms()),
        "families": FAMILIES,
    }
    target.write_text(
        json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    return target


