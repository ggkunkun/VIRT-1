def main():
    out_path = os.path.join(HERE, "dpo_concise_pairs.jsonl")
    n = 0
    with open(out_path, "w", encoding="utf-8") as f:
        for prompt, chosen, topic in PAIRS:
            rejected = war_report(topic)
            rec = {"prompt": prompt, "chosen": chosen, "rejected": rejected}
            f.write(json.dumps(rec, ensure_ascii=False) + "\n")
            n += 1
    # 统计
    clen = [len(p[1]) for p in PAIRS]
    rlen = [len(war_report(p[2])) for p in PAIRS]
    print(f"已写出 {n} 条简洁偏好对 -> {out_path}")
    print(f"chosen  字符数 median={sorted(clen)[n//2]} max={max(clen)}")
    print(f"rejected字符数 median={sorted(rlen)[n//2]} max={max(rlen)}")
    print(f"平均压缩比 ≈ {sum(rlen)/sum(clen):.1f}x")


if __name__ == "__main__":
    main()
